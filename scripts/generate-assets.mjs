// Generates TypeScript modules from the design package so the app keeps a single source of truth:
//   database/memora_sqlite.sql  -> src/db/schema.generated.ts
//   design/mascota/*.svg        -> src/components/Memo/poses.generated.ts
// Run with `npm run generate` after changing any of those files.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const header = '// AUTO-GENERATED by scripts/generate-assets.mjs. Do not edit by hand.\n';

const schema = readFileSync(join(root, 'database/memora_sqlite.sql'), 'utf8');
writeFileSync(
  join(root, 'src/db/schema.generated.ts'),
  `${header}export const SQLITE_SCHEMA = ${JSON.stringify(schema)};\n`,
);

// File names are in Spanish; identifiers in code are in English.
const poseNames = {
  hola: 'hello',
  estudiando: 'studying',
  reto: 'challenge',
  celebrando: 'celebrating',
  pensando: 'thinking',
  descanso: 'resting',
};
const mascotDir = join(root, 'design/mascota');
const poses = {};
for (const file of readdirSync(mascotDir).sort()) {
  const match = /^memo_(\w+)_(ambar|blanco)\.svg$/.exec(file);
  if (!match) continue;
  const pose = poseNames[match[1]];
  const tone = match[2];
  if (!pose) throw new Error(`Unknown mascot pose in ${file}`);
  poses[pose] ??= {};
  // The <Memo> wrapper owns accessibility, so the SVG's own role/aria-label are dropped
  // (react-native-svg forwards them to the DOM as invalid `ariaLabel` on web).
  const svg = readFileSync(join(mascotDir, file), 'utf8')
    .trim()
    .replace(/\s(role|aria-label)="[^"]*"/g, '');
  poses[pose][tone === 'ambar' ? 'amber' : 'white'] = svg;
}
writeFileSync(
  join(root, 'src/components/Memo/poses.generated.ts'),
  `${header}export const MEMO_POSES = ${JSON.stringify(poses, null, 2)} as const;\n`,
);

console.log(`schema: ${schema.length} chars · poses: ${Object.keys(poses).join(', ')}`);
