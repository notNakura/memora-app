// Teacher screens 24-28 connected to the session (withAccess, active institution) and to Expo Router.
// Screen 24 is the teacher shell's Resumen tab; 25-28 are stack screens under src/app/(app)/section/.
import { useLocalSearchParams, useRouter, type Href } from 'expo-router';
import { useMemo } from 'react';
import { Share } from 'react-native';
import { useSession } from '../auth/session';
import { InviteScreen } from './InviteScreen';
import { RequestsScreen } from './RequestsScreen';
import { SectionScreen } from './SectionScreen';
import { StudentScreen } from './StudentScreen';
import { TeacherDashboardScreen } from './TeacherDashboardScreen';
import { bindTeacherApi, teacherInstitutionFor, type TeacherClient } from './teacherClient';

// Typed routes (.expo/types) are generated by `expo start`; these paths exist under src/app/(app).
export const teacherHrefs = {
  dashboard: '/teacher' as Href,
  decks: '/teacher/decks' as Href,
  evaluations: '/teacher/evaluations' as Href,
  section: (sectionId: number) => `/section/${sectionId}` as Href,
  invite: (sectionId: number) => `/section/${sectionId}/invite` as Href,
  requests: (sectionId: number) => `/section/${sectionId}/requests` as Href,
  student: (sectionId: number, studentId: number) => `/section/${sectionId}/student/${studentId}` as Href,
};

/** Teacher API of the active teacher institution, or null while there is none. */
function useTeacherClient(): TeacherClient | null {
  const { user, activeInstitutionId, withAccess } = useSession();
  const institutionId = user ? teacherInstitutionFor(user.memberships, activeInstitutionId) : null;
  return useMemo(
    () => (institutionId === null ? null : bindTeacherApi(withAccess, institutionId)),
    [withAccess, institutionId],
  );
}

const toId = (raw: string | string[] | undefined) => {
  const value = Array.isArray(raw) ? raw[0] : raw;
  return value && /^[1-9]\d{0,9}$/.test(value) ? Number(value) : null;
};

function useBack() {
  const router = useRouter();
  return () => (router.canGoBack() ? router.back() : router.replace(teacherHrefs.dashboard));
}

/** Panel docente (24). */
export function TeacherDashboardRoute() {
  const { user } = useSession();
  const client = useTeacherClient();
  const router = useRouter();
  if (!user || !client) return null;
  const name = [user.firstNames, user.lastNames].filter(Boolean).join(' ');
  return (
    <TeacherDashboardScreen
      client={client}
      teacherName={name}
      onOpenSection={(id) => router.push(teacherHrefs.section(id))}
      // Crear evaluación (30) is built with the assessments; its tab shows the placeholder until then.
      onNewAssessment={() => router.navigate(teacherHrefs.evaluations)}
      onReviewDecks={() => router.navigate(teacherHrefs.decks)}
    />
  );
}

/** Mi sección (25). */
export function SectionRoute() {
  const client = useTeacherClient();
  const router = useRouter();
  const back = useBack();
  const sectionId = toId(useLocalSearchParams<{ sectionId: string }>().sectionId);
  if (!client || sectionId === null) return null;
  return (
    <SectionScreen
      client={client}
      sectionId={sectionId}
      onBack={back}
      onInvite={() => router.push(teacherHrefs.invite(sectionId))}
      onRequests={() => router.push(teacherHrefs.requests(sectionId))}
      onStudent={(studentId) => router.push(teacherHrefs.student(sectionId, studentId))}
      onUnits={() => router.navigate(teacherHrefs.dashboard)}
    />
  );
}

/** Invitar a la sección (26). */
export function InviteRoute() {
  const client = useTeacherClient();
  const back = useBack();
  const sectionId = toId(useLocalSearchParams<{ sectionId: string }>().sectionId);
  if (!client || sectionId === null) return null;
  return (
    <InviteScreen
      client={client}
      sectionId={sectionId}
      onBack={back}
      onShare={(url, code) => {
        Share.share({ message: `Únete a mi sección en Memora con el código ${code}: ${url}`, url }).catch(() => undefined);
      }}
    />
  );
}

/** Solicitudes de ingreso (27). */
export function RequestsRoute() {
  const client = useTeacherClient();
  const back = useBack();
  const sectionId = toId(useLocalSearchParams<{ sectionId: string }>().sectionId);
  if (!client || sectionId === null) return null;
  return <RequestsScreen client={client} sectionId={sectionId} onBack={back} />;
}

/** Desempeño del estudiante (28). */
export function StudentRoute() {
  const client = useTeacherClient();
  const back = useBack();
  const params = useLocalSearchParams<{ sectionId: string; studentId: string }>();
  const sectionId = toId(params.sectionId);
  const studentId = toId(params.studentId);
  if (!client || sectionId === null || studentId === null) return null;
  return <StudentScreen client={client} sectionId={sectionId} studentId={studentId} onBack={back} />;
}
