// Role shells: the tab bar each role sees once it has an active membership (docs/08_navegacion.md,
// "Arranque" and "Barras de navegación"). Each tab key is the route file
// of its tab under src/app/(app)/<shell>/; later flows replace the tab's placeholder with the real screen.
import type { Href } from 'expo-router';
import type { NavItem } from '../../components/BottomNav';
import { AssessIcon, DecksIcon, ProfileIcon, TodayIcon } from '../../components/icons';
import type { AppStartRoute } from '../auth/startRoute';
import { AreasIcon, ManagementIcon, ModerationIcon, SummaryIcon, UsersIcon } from './shellIcons';

export type ShellName = 'student' | 'teacher' | 'admin' | 'areaAdmin';

/** A tab of a shell: its route key, its label and the screens it holds (docs/04_pantallas.md numbers). */
export type ShellTab = NavItem & { title: string; screens: number[] };

/** Shell of a start screen, or null for the screens that open before a role (4, 5, 22, 33). */
export function shellFor(route: AppStartRoute): ShellName | null {
  switch (route.name) {
    case 'studentHome':
      return 'student';
    case 'teacherDashboard':
      return 'teacher';
    case 'institutionAdmin':
      return 'admin';
    case 'academicManagement':
      return 'areaAdmin';
    default:
      return null;
  }
}

