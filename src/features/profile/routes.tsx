// Screens 21 and 23 connected to the session and to Expo Router.
// Perfil (21) is the last tab of every shell; Ajustes y cuenta (23) and the guide (4, "Ayuda") are pushed.
import { useRouter, type Href } from 'expo-router';
import { useEffect } from 'react';
import { setVibrationEnabled } from '../../components/feedback';
import type { User } from '../../services/api/client';
import { useSession } from '../auth/session';
import { GuideScreen } from '../onboarding/GuideScreen';
import { preferencesOf, profileSubtitle } from './preferences';
import { ProfileScreen } from './ProfileScreen';
import { useProfileActions, useProfileUser } from './profileActions';
import { SettingsScreen } from './SettingsScreen';
import { useStreakInfo } from './useStreakInfo';
import { useSyncStatus } from './useSyncStatus';

// Typed routes (.expo/types) are generated by `expo start`; these paths exist under src/app/(app).
const MY_INSTITUTIONS = '/institutions' as Href;
const SETTINGS = '/settings' as Href;
const GUIDE = '/guide' as Href;

/** Keeps the tap vibration in line with app_user.vibration_enabled (RF-37). */
export function useApplyVibrationPreference(user: User | null) {
  const enabled = user ? preferencesOf(user).vibrationEnabled : true;
  useEffect(() => {
    setVibrationEnabled(enabled);
  }, [enabled]);
}

/** Perfil (21) of every shell. */
export function ProfileRoute() {
  const { activeInstitutionId, activeRole } = useSession();
  const user = useProfileUser();
  const { updatePreferences } = useProfileActions();
  const { status, sync } = useSyncStatus();
  const router = useRouter();
  useApplyVibrationPreference(user);
  if (!user) return null;
  return (
    <ProfileScreen
      user={user}
      subtitle={profileSubtitle(user, activeInstitutionId, activeRole)}
      sync={status}
      onSync={() => {
        sync().catch(() => undefined);
      }}
      onSavePreferences={updatePreferences}
      onOpenInstitutions={() => router.push(MY_INSTITUTIONS)}
      onOpenSettings={() => router.push(SETTINGS)}
    />
  );
}

/** Ajustes y cuenta (23), pushed from Perfil. */
export function SettingsRoute() {
  const { completeProfile, signOut } = useSession();
  const user = useProfileUser();
  const { updatePreferences, leaveSection } = useProfileActions();
  const streak = useStreakInfo();
  const router = useRouter();
  useApplyVibrationPreference(user);
  if (!user) return null;
  return (
    <SettingsScreen
      user={user}
      streak={streak}
      onBack={() => router.back()}
      onSavePreferences={updatePreferences}
      // PUT /me/profile needs the whole step-3 data: cédula and names go back unchanged.
      onSavePersonalData={({ birthDate, sex }) =>
        completeProfile({
          nationalId: user.nationalId ?? '',
          firstNames: user.firstNames ?? '',
          lastNames: user.lastNames ?? '',
          birthDate,
          sex,
        })
      }
      onLeaveSection={leaveSection}
      onOpenHelp={() => router.push(GUIDE)}
      onSignOut={() => signOut()}
    />
  );
}

/** The start guide reopened from "Ayuda y guía de inicio" (RF-53): finishing or "Saltar" goes back. */
export function HelpGuideRoute() {
  const router = useRouter();
  return (
    <GuideScreen
      onFinish={async () => {
        if (router.canGoBack()) router.back();
      }}
    />
  );
}
