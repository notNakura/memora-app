// Screens 4, 5, 22 and 33 connected to the session and to Expo Router. Each one is the start screen
// (no "Volver") or a screen pushed from another one (with "Volver"). When a join or a registration gives
// the person an active membership, pushed screens close so the start screen shows the new role.
import { useRouter, type Href } from 'expo-router';
import type { JoinOutcome } from '../../services/api/onboarding';
import { useSession } from '../auth/session';
import { MyInstitutionsScreen } from '../institutions/MyInstitutionsScreen';
import { RegisterInstitutionScreen } from '../institutions/RegisterInstitutionScreen';
import { JoinSectionScreen } from '../sections/JoinSectionScreen';
import { GuideScreen } from './GuideScreen';

// Typed routes (.expo/types) are generated by `expo start`; these paths exist under src/app/(app).
const JOIN_SECTION = '/join-section';
const MY_INSTITUTIONS = '/institutions' as Href;
const REGISTER_INSTITUTION = '/register-institution' as Href;
const joinSectionHref = (code?: string) => (code ? `${JOIN_SECTION}?code=${encodeURIComponent(code)}` : JOIN_SECTION) as Href;

type Pushed = { pushed?: boolean };

/** Back to the start screen, which already follows the refreshed user. */
function useBackToStart() {
  const router = useRouter();
  return () => {
    if (router.canDismiss()) router.dismissAll();
  };
}

export function GuideRoute() {
  const { completeOnboarding } = useSession();
  return <GuideScreen onFinish={completeOnboarding} />;
}

export function JoinSectionRoute({ pushed = false, initialCode }: Pushed & { initialCode?: string }) {
  const { user, previewSection, joinSection } = useSession();
  const router = useRouter();
  const backToStart = useBackToStart();
  if (!user) return null;
  return (
    <JoinSectionScreen
      user={user}
      initialCode={initialCode}
      onPreview={previewSection}
      onJoin={joinSection}
      onOpenInstitutions={() => router.push(MY_INSTITUTIONS)}
      onBack={pushed ? () => router.back() : undefined}
      onJoined={(outcome: JoinOutcome) => {
        if (outcome === 'active') backToStart();
      }}
    />
  );
}

export function MyInstitutionsRoute({ pushed = false }: Pushed) {
  const { user, signupChoice, activeInstitutionId, setActiveInstitution, joinInstitution } = useSession();
  const router = useRouter();
  if (!user) return null;
  return (
    <MyInstitutionsScreen
      user={user}
      activeInstitutionId={activeInstitutionId}
      signupChoice={signupChoice}
      onSelect={setActiveInstitution}
      onJoinInstitution={joinInstitution}
      onSectionCode={(code) => router.push(joinSectionHref(code))}
      onRegisterInstitution={() => router.push(REGISTER_INSTITUTION)}
      onBack={pushed ? () => router.back() : undefined}
    />
  );
}

export function RegisterInstitutionRoute({ pushed = false }: Pushed) {
  const { user, registerInstitution } = useSession();
  const router = useRouter();
  const backToStart = useBackToStart();
  if (!user) return null;
  return (
    <RegisterInstitutionScreen
      email={user.email}
      onRegister={async (input) => {
        await registerInstitution(input);
        backToStart();
      }}
      onBack={pushed ? () => router.back() : undefined}
    />
  );
}
